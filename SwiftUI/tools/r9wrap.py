#!/usr/bin/env python3
"""Routes calls from bare-metal armv7 code into iOS code through trampolines
that preserve r9.

Embedded Swift only targets bare-metal armv7 (armv7-apple-none-macho), where
r9 is callee-saved. On iOS, r9 is a scratch register that any function may
overwrite. Our Swift and C code is built with -ffixed-r9, so it never keeps
anything in r9, but the prebuilt runtime archives (libswift_Concurrency.a)
are not: iOS 6's malloc, for one, returns with r9 = 0xffffffff, and the
runtime then crashes using the value it kept there.

For every function that bare-metal code calls but doesn't define (libSystem
functions and the UIKit backend's sui_* functions), this writes a trampoline
`_r9$name` that saves r9, calls `name` and restores r9, and copies each
bare-metal object and archive with its references renamed to the trampoline.

usage: r9wrap.py OUT_DIR HEADER[,HEADER...] OBJECT_OR_ARCHIVE...
HEADER declares the iOS-side functions Swift calls (SwiftUIBackend.h, and an
app's own C API), so trampolines know which take stack arguments.
Writes OUT_DIR/trampolines.s and OUT_DIR/<basename> for each input.
"""

import os
import re
import subprocess
import sys

OBJCOPY = os.environ.get("LLVM_OBJCOPY", "llvm-objcopy")

# Data, not functions: references to these are left alone.
DATA = {
    "___stack_chk_guard",
    "___stderrp",
}


def stack_args(headers):
    """Words each function declared in `headers` takes on the stack, beyond
    r0-r3. Their arguments must all be pointers or longs. The libSystem
    functions the runtime calls all take at most four words."""
    text = "".join(open(header).read() for header in headers)
    counts = {}
    for name, params in re.findall(r"\b(\w+)\(([^()]*)\);", text):
        params = params.strip()
        count = 0 if params in ("", "void") else params.count(",") + 1
        counts["_" + name] = max(0, count - 4)
    return counts


def symbols(paths, *flags):
    output = subprocess.run(["nm", *flags, *paths], capture_output=True, text=True).stdout
    names = set()
    for line in output.splitlines():
        fields = line.split()
        if not fields or line.endswith(":") or "no symbols" in line:
            continue
        names.add(fields[-1])
    return names


def trampoline(name, stack):
    # Keep sp 8-byte aligned at the call.
    frame = (stack * 4 + 7) & ~7
    lines = [
        f".globl _r9${name[1:]}",
        ".p2align 2",
        f"_r9${name[1:]}:",
        "    push {r9, lr}",
    ]
    if frame:
        lines.append(f"    sub sp, sp, #{frame}")
        for i in range(stack):
            # Caller's stack arguments start above the saved r9 and lr.
            lines.append(f"    ldr r12, [sp, #{frame + 8 + 4 * i}]")
            lines.append(f"    str r12, [sp, #{4 * i}]")
    lines.append(f"    blx {name}")
    if frame:
        lines.append(f"    add sp, sp, #{frame}")
    lines.append("    pop {r9, pc}")
    return "\n".join(lines) + "\n"


def main():
    out_dir, header, inputs = sys.argv[1], sys.argv[2], sys.argv[3:]
    stack = stack_args([h for h in header.split(",") if h])
    os.makedirs(out_dir, exist_ok=True)

    defined = symbols(inputs, "-g", "-U", "-j")
    undefined = symbols(inputs, "-u", "-j")
    wrapped = sorted(n for n in undefined - defined if n not in DATA)

    with open(os.path.join(out_dir, "trampolines.s"), "w") as f:
        f.write("// Generated by tools/r9wrap.py. Calls into iOS code that preserve r9.\n")
        f.write(".text\n.arm\n.subsections_via_symbols\n\n")
        for name in wrapped:
            f.write(trampoline(name, stack.get(name, 0)) + "\n")

    renames = os.path.join(out_dir, "renames.txt")
    with open(renames, "w") as f:
        for name in wrapped:
            f.write(f"{name} _r9${name[1:]}\n")
    for path in inputs:
        out = os.path.join(out_dir, os.path.basename(path))
        subprocess.run([OBJCOPY, f"--redefine-syms={renames}", path, out], check=True)


if __name__ == "__main__":
    main()
